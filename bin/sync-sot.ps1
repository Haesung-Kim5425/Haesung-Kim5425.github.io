        if ($LASTEXITCODE -ne 0) {
            Write-Warning "make-figure-panel.py failed (exit $LASTEXITCODE). The panel on the front page is now out of date."
        }
        else {
            [System.IO.File]::WriteAllText($stampPath, $figStamp, (New-Object System.Text.UTF8Encoding($false)))
            Write-Host "Selected-work panel rebuilt." -ForegroundColor Green
        }
        $wroteSomething = $true
    }
    else {
        Write-Warning "python not found, so the selected-work panel was not rebuilt. Run: python bin/make-figure-panel.py"
    }
}

if (-not $wroteSomething) {
    # Deliberately write nothing when both artefacts already match. An earlier version
    # rewrote the bibliography just to refresh its header timestamp, which left a one-line
    # diff after every run -- and a file that is always modified is a file whose diffs
    # stop being read, on exactly the file where a diff must always mean something.
    Write-Host "Already current; nothing written." -ForegroundColor Green
}
