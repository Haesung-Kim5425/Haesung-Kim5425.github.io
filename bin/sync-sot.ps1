<#
.SYNOPSIS
    Copies the academic record's artefacts into the site. One-way, record -> site.

.DESCRIPTION
    What the site publishes is produced outside this repository, by the session that owns
    the academic record:

        ../achievements/publications.bib   -> _bibliography/papers.bib
        ../achievements/profile.yml        -> _data/profile.yml
                                           -> _data/socials.yml   (generated from it)
        ../cv/Haesung_Kim_CV.pdf           -> assets/pdf/Haesung_Kim_CV.pdf

    All of it has to be copied in. jekyll-scholar can only read a .bib inside the site root,
    and the GitHub Actions build only ever checks out this repository -- so nothing
    downstream can notice if a copy falls behind its source. This script is that copy, and
    it is the ONLY sanctioned way for either destination to change.

    Run it before every commit that touches publications or the CV. It is safe to run
    repeatedly: it writes nothing when both artefacts already match.

.NOTES
    Direction is one-way by design. Edits made directly to _bibliography/papers.bib are
    destroyed the next time this runs. Fix the SoT instead.

    Exit codes:
      0  synced, or (-Check) the copy is current
      1  the source could not be found
      2  (-Check only) the copy is stale and needs a sync
      3  the source is not valid BibTeX and was refused; -Repair overrides
#>

[CmdletBinding()]
param(
    # Path to the SoT .bib. Defaults to the hub's achievements/ directory, two levels up.
    [string]$SotPath,

    # Where jekyll-scholar reads from (see `scholar.bibliography` in _config.yml).
    [string]$DestPath,

    # The CV PDF, generated by the hub session from the same academic record.
    [string]$CvSourcePath,
    [string]$CvDestPath,

    # Publication figures, referenced by `preview` fields in the bibliography.
    [string]$FigSourceDir,
    [string]$FigDestDir,

    # The machine-readable profile: name, position, contact, ids, style rules, bio, metrics.
    [string]$ProfileSourcePath,
    [string]$ProfileDestPath,

    # The machine-readable record: teaching, conferences, awards, grants, patents.
    [string]$RecordSourcePath,
    [string]$RecordDestPath,

    # Generated from the profile above; consumed by jekyll-socials.
    [string]$SocialsPath,

    # Report what would change without writing anything.
    [switch]$Check,

    # Sync anyway when the source contains '@' inside a '%' comment line, rewriting those
    # '@' to '[at]' in the copy only. Off by default on purpose -- see the check below.
    [switch]$Repair
)

$ErrorActionPreference = 'Stop'

# Resolve the script's own directory in the body, not in a param() default.
# $PSScriptRoot is not populated during parameter binding when the script is launched as
# `powershell -File bin/sync-sot.ps1` (which is how the git pre-commit hook calls it), so
# a Join-Path default there fails with "Cannot bind argument to parameter 'Path'".
$here = Split-Path -Parent $MyInvocation.MyCommand.Path
if (-not $SotPath)      { $SotPath      = Join-Path $here '..\..\achievements\publications.bib' }
if (-not $DestPath)     { $DestPath     = Join-Path $here '..\_bibliography\papers.bib' }
if (-not $CvSourcePath) { $CvSourcePath = Join-Path $here '..\..\cv\Haesung_Kim_CV.pdf' }
if (-not $CvDestPath)   { $CvDestPath   = Join-Path $here '..\assets\pdf\Haesung_Kim_CV.pdf' }
if (-not $FigSourceDir) { $FigSourceDir = Join-Path $here '..\..\achievements\figures' }
if (-not $FigDestDir)   { $FigDestDir   = Join-Path $here '..\assets\img\publication_preview' }
if (-not $ProfileSourcePath) { $ProfileSourcePath = Join-Path $here '..\..\achievements\profile.yml' }
if (-not $ProfileDestPath)   { $ProfileDestPath   = Join-Path $here '..\_data\profile.yml' }
if (-not $RecordSourcePath)  { $RecordSourcePath  = Join-Path $here '..\..\achievements\record.yml' }
if (-not $RecordDestPath)    { $RecordDestPath    = Join-Path $here '..\_data\record.yml' }
if (-not $SocialsPath)       { $SocialsPath       = Join-Path $here '..\_data\socials.yml' }

# --------------------------------------------------------------------------------------
# Refuse to run if a file the record marks as NOT publishable has been copied in here.
#
# achievements/exclude_private.yml lists the strings that must never be published --
# manuscript ids, a collaborator, sample codenames. It is deliberately kept outside this
# repository, because a list of secrets stored in a public repository publishes exactly
# what it exists to withhold. bin/check-public.ps1 reads it in place, across the repo
# boundary, and nothing copies it.
#
# The failure this guards against is someone (including a later version of this script)
# copying it in for convenience. Checked by name anywhere in the tree, and by declaration
# in _data, which is where a copy would most plausibly land.
# --------------------------------------------------------------------------------------
$siteRootPath = (Resolve-Path -LiteralPath (Join-Path $here '..')).Path
$strayPrivate = @()
$strayPrivate += Get-ChildItem -LiteralPath $siteRootPath -Recurse -File -Filter 'exclude_private.yml' -ErrorAction SilentlyContinue |
    Where-Object { $_.FullName -notmatch '(?i)[\/](\.git|_site.*|node_modules|vendor)[\/]' }
$dataDirPath = Join-Path $siteRootPath '_data'
if (Test-Path -LiteralPath $dataDirPath) {
    $strayPrivate += Get-ChildItem -LiteralPath $dataDirPath -Recurse -File -Include *.yml, *.yaml -ErrorAction SilentlyContinue |
        Where-Object { (Get-Content -LiteralPath $_.FullName -Raw -Encoding UTF8) -match '(?m)^\s*public_safe\s*:\s*false\s*(#.*)?$' }
}
if ($strayPrivate.Count -gt 0) {
    Write-Host ""
    Write-Host "SYNC REFUSED - a file marked 'public_safe: false' is inside the public repository." -ForegroundColor Red
    foreach ($f in ($strayPrivate | Select-Object -Unique FullName)) { Write-Host "  $($f.FullName)" }
    Write-Host ""
    Write-Host "  Delete it. It belongs in achievements/ only, and is read from there across the"
    Write-Host "  repository boundary. Committing it would publish the very strings it withholds."
    Write-Host ""
    exit 3
}

if (-not (Test-Path -LiteralPath $SotPath)) {
    Write-Error "SoT not found: $SotPath`nThe hub session owns this file. Ask it to create the file before syncing."
    exit 1
}

$SotPath  = (Resolve-Path -LiteralPath $SotPath).Path
$destDir  = Split-Path -Parent $DestPath
if (-not (Test-Path -LiteralPath $destDir)) { New-Item -ItemType Directory -Path $destDir | Out-Null }

$sotText = Get-Content -LiteralPath $SotPath -Raw -Encoding UTF8
if ($null -eq $sotText) { $sotText = '' }
# Drop a leading BOM: it would otherwise end up mid-file, after the header we prepend.
# (Written as an escape, not a literal, so this script stays pure ASCII on disk --
#  Windows PowerShell 5.1 reads a BOM-less .ps1 as ANSI and would corrupt a literal.)
$sotText = $sotText.TrimStart([char]0xFEFF)

# Normalise line endings to LF.
#
# .gitattributes pins *.bib to LF in the working tree, so that is what a checkout or a
# fresh clone produces. If the copy were written with whatever the source happens to use,
# a source containing even one CRLF would make every clone differ from its own sync
# output: sync rewrites it with CRLF, git checks it back out as LF, sync rewrites it
# again -- the permanently-modified file this script was already fixed once to avoid.
# The source does currently contain a stray CRLF, so this is not hypothetical.
#
# Line endings are not content for BibTeX or YAML, so normalising loses nothing.
$sotText = $sotText -replace "`r`n", "`n"

# Refuse to sync a source that is not valid BibTeX. Fail loudly; do not paper over it.
#
# BibTeX has no line-comment syntax: '%' lines are simply text outside any entry, and
# bibtex-ruby skips them by scanning forward to the next '@'. So an '@' that appears
# inside a '%' note -- e.g. a tally line reading "total 24 = @article 21 + ..." -- makes
# the parser open an entry mid-comment and the whole file fails with
#   Failed to parse BibTeX on value "21" (NUMBER) ["@", "article"]
# taking the publications page down with it. This happened for real on 2026-08-07.
#
# An earlier version of this script silently rewrote those '@' and carried on. That was
# the wrong call: the same file is also read by the CV and biosketch renderers, which
# have no such workaround, so a quiet fix here would have let a broken source sit
# unnoticed until it broke somewhere with no guard rail. The source is the thing to fix.
#
# -Repair applies the old rewrite as a deliberate, one-off escape hatch. Only comment
# lines are touched either way, so no entry field, author, title or DOI can be altered.
$commentAtPattern = '(?m)^([ \t]*%.*)$'
$offending = [regex]::Matches($sotText, $commentAtPattern) | Where-Object { $_.Groups[1].Value.Contains('@') }

if ($offending.Count -gt 0) {
    if (-not $Repair) {
        Write-Host ""
        Write-Host "SYNC REFUSED - the publication source of truth is not valid BibTeX." -ForegroundColor Red
        Write-Host ""
        Write-Host "  $($offending.Count) comment line(s) contain '@'. BibTeX has no line-comment syntax, so a"
        Write-Host "  parser treats '%' text as 'skip to the next @' and opens an entry mid-comment."
        Write-Host "  The whole file then fails to parse - not just here, but in every renderer that"
        Write-Host "  reads it (CV, biosketch)."
        Write-Host ""
        Write-Host "  Offending line(s) in $SotPath :" -ForegroundColor Yellow
        foreach ($m in $offending) {
            $lineNo = ($sotText.Substring(0, $m.Index) -split "`n").Count
            $text   = $m.Groups[1].Value.Trim()
            if ($text.Length -gt 100) { $text = $text.Substring(0, 100) + '...' }
            Write-Host "    line $lineNo : $text"
        }
        Write-Host ""
        Write-Host "  Fix the source: write 'journal article' instead of '@article' in comments."
        Write-Host "  To sync anyway with '@' rewritten to '[at]' in the copy only:  -Repair"
        Write-Host ""
        exit 3
    }

    Write-Warning "$($offending.Count) comment line(s) in the SoT contain '@'. -Repair given: rewriting them to '[at]' in the copy."
    Write-Warning "This does not fix the source. Other renderers of the same file will still fail on it."
    $sotText = [regex]::Replace($sotText, $commentAtPattern, {
        param($m)
        $line = $m.Groups[1].Value
        if ($line.Contains('@')) { $line.Replace('@', '[at]') } else { $line }
    })
}

# Count real BibTeX entries so the operator sees whether the site will actually have
# anything to show. @string / @preamble / @comment are not publications.
$entryMatches = [regex]::Matches($sotText, '(?m)^\s*@(?!string\b|preamble\b|comment\b)([A-Za-z]+)\s*\{')
$entryCount   = $entryMatches.Count
$byType = $entryMatches | Group-Object { $_.Groups[1].Value.ToLower() } | Sort-Object Name

# --------------------------------------------------------------------------------------
# Publication statistics -> _data/pubstats.yml
#
# The page needs "N papers, n as primary author, m as co-author". Those numbers must never
# be typed into the page: they change with every publication, and a hand-written count
# that nobody updates is a false claim on a public academic page. They are counted from
# the bibliography here, on every sync, so they cannot drift from the list beside them.
#
# Primary authorship is taken from the `authorship` field when the entry has one, and
# from the author list position when it does not. Both are computed either way and a
# disagreement is reported: the field is the source of truth, and position is the check
# on it. Entries carrying no `authorship` at all are counted separately rather than
# silently assumed to be co-authored -- "not recorded" and "co-author" are different
# facts, and collapsing them is how a record quietly loses information.
# --------------------------------------------------------------------------------------
$ownerNames = @('Kim, Haesung', 'Kim, Hae Sung')
$statEntries = [regex]::Matches($sotText, '(?ms)^@(?!string\b|preamble\b|comment\b)([A-Za-z]+)\s*\{(.*?)(?=^@|\z)')

$stat = [ordered]@{
    total = 0; article = 0; inproceedings = 0; misc = 0
    preprint = 0; peer_reviewed = 0
    primary = 0; co_author = 0
    role_first = 0; role_co_first = 0; role_corresponding = 0; role_co_author = 0; role_unrecorded = 0
}
$roleMismatch = @()

foreach ($m in $statEntries) {
    $type = $m.Groups[1].Value.ToLower()
    $body = $m.Groups[2].Value
    $stat.total++
    if ($stat.Contains($type)) { $stat[$type]++ }

    $isPreprint = $body -match '(?ms)keywords\s*=\s*\{[^}]*preprint'
    if ($isPreprint) { $stat.preprint++ } else { $stat.peer_reviewed++ }

    # Author position. The field spans lines, so match across them.
    $authorField = ([regex]::Match($body, '(?ms)author\s*=\s*\{(.*?)\}')).Groups[1].Value
    $authors = ($authorField -replace '\s+', ' ') -split '\s+and\s+'
    $pos = 0
    for ($i = 0; $i -lt $authors.Count; $i++) {
        $a = $authors[$i].Trim()
        foreach ($n in $ownerNames) { if ($a.StartsWith($n)) { $pos = $i + 1; break } }
        if ($pos) { break }
    }

    $roleField = ([regex]::Match($body, '(?ms)authorship\s*=\s*\{([^}]*)\}')).Groups[1].Value
    $hasRole = -not [string]::IsNullOrWhiteSpace($roleField)
    if ($hasRole) {
        if ($roleField -match 'co-first')      { $stat.role_co_first++ }
        if ($roleField -match 'corresponding') { $stat.role_corresponding++ }
        if ($roleField -match '(^|,)\s*first') { $stat.role_first++ }
        if ($roleField -match 'co-author')     { $stat.role_co_author++ }
    }
    else { $stat.role_unrecorded++ }

    # Primary = first-listed author, or shared first authorship.
    $primaryByPosition = ($pos -eq 1)
    $primaryByField    = $hasRole -and ($roleField -match 'co-first' -or $roleField -match '(^|,)\s*first' -or $roleField -match 'corresponding')
    $isPrimary = if ($hasRole) { $primaryByField -or $primaryByPosition } else { $primaryByPosition }
    # Count roles over peer-reviewed papers only, so primary + co_author == peer_reviewed.
    #
    # These two numbers are rendered in one sentence beside the peer-reviewed total. When
    # roles were counted over every entry and the total excluded the preprint, the sentence
    # read "25 peer-reviewed papers - 14 as primary author, 12 as co-author": the preprint
    # is co-authored, so it landed on one side of a sum whose total had already dropped it.
    # 14 + 12 = 26, and any reader who added them up saw it. A generated number is only
    # right if it is also counted over the same population as the number beside it.
    if (-not $isPreprint) {
        if ($isPrimary) { $stat.primary++ } else { $stat.co_author++ }
    }

    # Only flag a disagreement that would actually mean an error. Shared first authorship
    # and corresponding authorship are both routinely held by someone who is not listed
    # first -- that is the normal case, not a contradiction, so neither is reported.
    # Flagging them made the check fire on a correct record, which is how a check earns
    # being ignored.
    $legitimatelyNotFirst = ($roleField -match 'co-first' -or $roleField -match 'corresponding') -and ($pos -ne 1)
    if ($hasRole -and ($primaryByField -ne $primaryByPosition) -and -not $legitimatelyNotFirst) {
        $key = ([regex]::Match($body, '^([^,]*),')).Groups[1].Value.Trim()
        $roleMismatch += "$key : authorship='$roleField' but author position is $pos"
    }
}

# Selected papers must be first-authored. The owner's rule, narrowed twice: first from
# "any primary author" after a seventeen-author paper was featured for the journal's sake,
# then to first-author-only, which excludes corresponding authorship and shared first
# authorship where the owner is not listed first.
#
# Enforced rather than trusted, because the failure mode is a person deciding a paper is
# too prestigious to leave out -- which is exactly how the first violation happened. The
# CV generator refuses to build on the same condition; if only one of the two refused, the
# public site would be the one that published the violation.
$selectedViolations = @()
foreach ($m in $statEntries) {
    $body = $m.Groups[2].Value
    if ($body -notmatch '(?ms)selected\s*=\s*\{true\}') { continue }
    $r = ([regex]::Match($body, '(?ms)authorship\s*=\s*\{([^}]*)\}')).Groups[1].Value
    $tokens = ($r -replace '\s', '') -split ','
    if ($tokens -notcontains 'first') {
        $k = ([regex]::Match($body, '^([^,]*),')).Groups[1].Value.Trim()
        $selectedViolations += "$k : selected={true} but authorship='$r' (not first-authored)"
    }
}
if ($selectedViolations.Count -gt 0) {
    Write-Host ""
    Write-Host "SYNC REFUSED - a selected paper is not first-authored." -ForegroundColor Red
    Write-Host ""
    foreach ($v in $selectedViolations) { Write-Host "    $v" -ForegroundColor Yellow }
    Write-Host ""
    Write-Host "  Selected papers are first-author-only (owner's rule, 2026-08-08). Corresponding"
    Write-Host "  authorship and shared first authorship where the owner is not listed first do not"
    Write-Host "  qualify, and journal prestige is not a reason. Fix the source, not this check."
    Write-Host ""
    exit 3
}

# Arithmetic self-check on the numbers that end up in one sentence together.
#
# "Do not hardcode the count" is not enough on its own. The figures here were always
# freshly computed and still wrong, because two of them were counted over different
# populations. Three things have to hold, and only the first was ever being enforced:
# the value is current, it is counted over the same population as the value beside it,
# and the parts add up. This is the third.
#
# Refuses rather than warns: the failure is a public page stating a sum that does not
# add, which any reader can check in their head.
$sumParts = $stat.primary + $stat.co_author
if ($sumParts -ne $stat.peer_reviewed) {
    Write-Host ""
    Write-Host "SYNC REFUSED - publication statistics do not add up." -ForegroundColor Red
    Write-Host ""
    Write-Host "    primary ($($stat.primary)) + co_author ($($stat.co_author)) = $sumParts"
    Write-Host "    peer_reviewed = $($stat.peer_reviewed)"
    Write-Host ""
    Write-Host "  These three are rendered in one sentence on the publications page, so the"
    Write-Host "  mismatch is visible to anyone who adds them. Usually it means a category was"
    Write-Host "  counted over a different population - a preprint included on one side and"
    Write-Host "  excluded from the other, for instance."
    Write-Host ""
    exit 3
}
if (($stat.article + $stat.inproceedings) -ne $stat.peer_reviewed) {
    Write-Warning "article ($($stat.article)) + inproceedings ($($stat.inproceedings)) != peer_reviewed ($($stat.peer_reviewed)). The page prints both breakdowns; they should agree."
}

if ($roleMismatch.Count -gt 0) {
    Write-Warning "authorship field disagrees with author position in $($roleMismatch.Count) entry(ies):"
    foreach ($r in $roleMismatch) { Write-Warning "    $r" }
}

$statsYaml = @"
# ============================================================================
# GENERATED FILE - DO NOT EDIT.
#
# Counted from the bibliography by bin/sync-sot.ps1 on every sync, so these numbers
# cannot drift from the list they describe. Never write a publication count into a page
# by hand: it is wrong the day the next paper appears, and nobody notices.
#
# primary         = first-listed author, or shared first authorship, or corresponding
# co_author       = everything else
# role_unrecorded = entries with no authorship field at all. Not the same as
#                   co-authored - it means the record does not say.
#
# NOTE: no backticks in this block. It lives in a PowerShell double-quoted here-string,
# where a backtick is the escape character - "authorship" written with backticks around
# it emitted a literal BEL (0x07) into the file, and YAML refuses to parse a control
# character, taking the whole site build down with it.
# ============================================================================

total: $($stat.total)
article: $($stat.article)
inproceedings: $($stat.inproceedings)
misc: $($stat.misc)
peer_reviewed: $($stat.peer_reviewed)
preprint: $($stat.preprint)
primary: $($stat.primary)
co_author: $($stat.co_author)
role_first: $($stat.role_first)
role_co_first: $($stat.role_co_first)
role_corresponding: $($stat.role_corresponding)
role_co_author: $($stat.role_co_author)
role_unrecorded: $($stat.role_unrecorded)
"@

$statsPath = Join-Path $here '..\_data\pubstats.yml'
$statsOld = ''
if (Test-Path -LiteralPath $statsPath) { $statsOld = Get-Content -LiteralPath $statsPath -Raw -Encoding UTF8 }
$statsChanged = ($statsOld -ne $statsYaml)

$stamp = (Get-Date).ToString('yyyy-MM-dd HH:mm:ss')
$header = @"
% ============================================================================
% GENERATED FILE - DO NOT EDIT.
%
% Copied from the publication source of truth (entries verbatim, its comments left there):
%     achievements/publications.bib   (owned by the Academic Profile hub session)
%
% Any edit made here is overwritten the next time bin/sync-sot.ps1 runs. To change
% what the website shows, change the SoT and re-run:
%
%     pwsh -File bin/sync-sot.ps1
%
% Synced: $stamp   |   entries: $entryCount
% ============================================================================

"@

# The bibliography's own comments stay with the hub too, for the reason above: the SoT
# carries a Korean provenance header -- which author name was corrected and on whose
# authority, which DOI belongs to a different person of the same name -- and this copy is
# published. BibTeX ignores text outside entries, so removing those lines changes nothing
# that is read. The refusal above still examines them in the SOURCE, where they exist:
# the CV and the biosketch parse the annotated original, and an '@' in a comment breaks
# them whatever this copy looks like.
$sotText = ($sotText -split "`n" | Where-Object { -not $_.TrimStart().StartsWith('%') }) -join "`n"

$newText = $header + $sotText

$oldBody = ''
if (Test-Path -LiteralPath $DestPath) {
    $oldRaw = Get-Content -LiteralPath $DestPath -Raw -Encoding UTF8
    if ($null -ne $oldRaw) {
        # Strip a previously generated header so an unchanged SoT does not look like a diff.
        #
        # Match through the closing banner line and its single line break. Do not require a
        # blank line after it: PowerShell here-strings drop the newline before the closing
        # "@, so the header ends with exactly one newline. Requiring two made this never
        # match, which reported every file as changed and would have made the pre-commit
        # freshness check block every commit.
        $oldBody = [regex]::Replace($oldRaw, '(?s)^% =+.*?^% =+[ \t]*\r?\n', '', 'Multiline')
    }
}

$changed = ($oldBody -ne $sotText)

Write-Host "SoT   : $SotPath"
Write-Host "Site  : $DestPath"
Write-Host "Entries: $entryCount" -NoNewline
if ($byType) { Write-Host ("  (" + (($byType | ForEach-Object { "$($_.Name)=$($_.Count)" }) -join ', ') + ")") } else { Write-Host "" }

if ($entryCount -eq 0) {
    Write-Warning "The SoT contains no BibTeX entries. The Publications page will render EMPTY."
    Write-Warning "Ask the hub session to run the ORCID -> Zotero -> DOI-verification sync first."
}

# --------------------------------------------------------------------------------------
# CV PDF
#
# Second artefact copied in from outside the repo, for the same reason as the
# bibliography: the hub session generates it from the same academic record, and the
# GitHub Actions build only checks out this repository. Compared by hash, because a PDF
# regenerated from unchanged input still differs byte-for-byte (timestamps), and copying
# it every time would leave a permanently modified binary in git history.
# --------------------------------------------------------------------------------------
$cvChanged  = $false
$cvPresent  = Test-Path -LiteralPath $CvSourcePath

function Get-FileHashOrNull($path) {
    if (Test-Path -LiteralPath $path) { return (Get-FileHash -LiteralPath $path -Algorithm SHA256).Hash }
    return $null
}

if ($cvPresent) {
    $CvSourcePath = (Resolve-Path -LiteralPath $CvSourcePath).Path
    $srcHash = Get-FileHashOrNull $CvSourcePath
    $dstHash = Get-FileHashOrNull $CvDestPath
    $cvChanged = ($srcHash -ne $dstHash)
    Write-Host "CV    : $CvSourcePath"
    Write-Host "     -> $CvDestPath" -NoNewline
    if ($cvChanged) { Write-Host "  [differs]" -ForegroundColor Yellow } else { Write-Host "  [current]" }
}
else {
    # Not an error. The CV is generated by the hub session and may simply not exist on
    # this machine; the site keeps its committed copy and the /cv/ page still works.
    Write-Host "CV    : source not found at $CvSourcePath -- leaving the committed copy alone."
}

# --------------------------------------------------------------------------------------
# Profile (name, position, contact, ids, style rules, bio, metrics)
#
# Unlike the bibliography, this file carries contact details, and it is copied into a
# PUBLIC repository. Two gates before anything is written:
#
#   1. meta.public_safe must be literally true. The record's author sets it, and it is an
#      explicit statement that the file was written to be published. Absent or false, the
#      sync refuses rather than assuming.
#   2. An independent scan for the things the record says must never be published. Gate 1
#      is a claim; this is a check. The point of a second gate is that it does not trust
#      the first.
#
# The site's _data/socials.yml is then GENERATED from it, so the email, ORCID and Scholar
# id exist in exactly one place across the whole system.
# --------------------------------------------------------------------------------------
# Render LaTeX-style subscripts as real subscript characters.
#
# The record writes chemical formulae the way the CV needs them for .tex: HfZrO_x, SiN_x,
# Si-SiO_2. On a web page the underscore arrives literally -- "HfZrO_x" was live on the
# research page, because the previous pass verified only the opening sentence of a
# paragraph whose formulae are all in the last two.
#
# Only "letter + underscore + digit-or-x" is converted, so a YAML key can never be hit.
# Checked before enabling: of 62 keys in profile.yml and 46 in record.yml, none matches
# that shape; the only matches anywhere are the formulae themselves.
#
# Typography, not wording. The approved text is unchanged -- this is the same class of
# change as the en-dash conversion, and the real fix remains a record that holds
# renderer-neutral text.
function Convert-Subscripts {
    param([string]$Text)
    # Real subscript characters, written as escapes so this script stays pure ASCII on
    # disk -- Windows PowerShell 5.1 reads a BOM-less .ps1 as ANSI and would corrupt
    # literals. HTML entities would work in the page but would leave "&#8322;" sitting in
    # the data file for any non-HTML consumer of the same record.
    $map = @{}
    0..9 | ForEach-Object { $map["$_"] = [char](0x2080 + $_) }
    $map['x'] = [char]0x2093
    return [regex]::Replace($Text, '([A-Za-z])_([0-9x])', {
        param($m)
        $m.Groups[1].Value + $map[$m.Groups[2].Value]
    })
}

# Shared gate for every YAML the record hands over. Written once and used for both
# profile.yml and record.yml: duplicated safety logic is the kind that drifts, and the
# copy that stops being maintained is the one still guarding something.
# Drop full-line comments when copying a record into this repository.
#
# The records are commented in Korean by the hub session, and those comments are working
# notes: which values are withheld and why, what the owner approved on which date, what a
# renderer must not do. This repository is public, so copying them verbatim publishes the
# editorial reasoning behind the page -- including, in one case, a token from the private
# block list, quoted in a note explaining that it must not be published.
#
# It is the same rule this site already enforces on page sources, where an internal note
# must be a Liquid comment rather than an HTML one: notes stop at the boundary. Nothing is
# lost, because the copies are read by Liquid, which never sees a comment anyway, and the
# annotated original stays with the hub.
#
# Block scalars are tracked, because inside one a line starting with '#' is text, not a
# comment. The safety of that is not argued -- it is verified: the parsed structure of the
# copy is compared with the parsed structure of the source. See bin/verify-strip.py.
function Remove-CommentLines {
    param([string]$Text)

    $out = New-Object System.Collections.Generic.List[string]
    $blockIndent = -1
    $lastBlank = $false
    foreach ($raw in ($Text -split "`n")) {
        $line = $raw.TrimEnd([char]13)
        $trimmed = $line.Trim()
        $indent = $line.Length - $line.TrimStart().Length

        if ($blockIndent -ge 0) {
            if ($trimmed -eq '' -or $indent -gt $blockIndent) { $out.Add($line); $lastBlank = ($trimmed -eq ''); continue }
            $blockIndent = -1
        }
        if ($trimmed.StartsWith('#')) { continue }
        # Collapse the blank runs the removed comments leave behind, outside block scalars
        # where a blank line is part of the text.
        if ($trimmed -eq '') {
            if ($lastBlank -or $out.Count -eq 0) { continue }
            $lastBlank = $true
            $out.Add('')
            continue
        }
        $lastBlank = $false
        if ($line -match ':\s*[|>][-+0-9]*\s*$') { $out.Add($line); $blockIndent = $indent; continue }

        # Trailing comments as well. Half the notes in these records are written after a
        # value rather than above it, and a rule that removed only whole lines would leave
        # them -- publishing the same reasoning one column to the right.
        #
        # Quote state is tracked so that a '#' inside a value survives. Whether that is
        # done correctly is not taken on trust: bin/verify-strip.py parses both files and
        # compares the structures, so a mangled value shows up as a changed value.
        $cut = -1
        $inSingle = $false
        $inDouble = $false
        for ($i = 0; $i -lt $line.Length; $i++) {
            $ch = $line[$i]
            if ($ch -eq "'" -and -not $inDouble) { $inSingle = -not $inSingle }
            elseif ($ch -eq '"' -and -not $inSingle) { $inDouble = -not $inDouble }
            elseif ($ch -eq '#' -and -not $inSingle -and -not $inDouble -and $i -gt 0 -and ($line[$i - 1] -eq ' ' -or $line[$i - 1] -eq [char]9)) {
                $cut = $i
                break
            }
        }
        if ($cut -ge 0) {
            $line = $line.Substring(0, $cut).TrimEnd()
            if ($line.Trim() -eq '') { continue }
        }
        $out.Add($line)
    }
    return ($out -join "`n")
}

function Assert-PublicSafe {
    param([string]$Text, [string]$Label, [string]$Path)

    if ($Text -notmatch '(?m)^\s*public_safe\s*:\s*true\s*(#.*)?$') {
        Write-Host ""
        Write-Host "SYNC REFUSED - $Label is not marked public_safe." -ForegroundColor Red
        Write-Host "  $Path"
        Write-Host ""
        Write-Host "  This file is copied into a public repository. It is only copied when its author"
        Write-Host "  has declared it safe to publish, with 'public_safe: true' under meta."
        Write-Host ""
        exit 3
    }

    # Values that must never be published. Patterns are deliberately narrow: an earlier
    # version matched an ORCID as a phone number, and the hub's equivalent matched a
    # patent application number. Identifiers are all hyphenated digit groups, so a loose
    # phone pattern catches them, and a gate that rejects a correct file gets switched off.
    $forbidden = @(
        @{ name = 'phone number';    pattern = '(?<!\d)\+\d{1,3}[-. ]\d{2,4}[-. ]\d{3,4}[-. ]\d{3,4}(?!\d)' },
        @{ name = 'phone number';    pattern = '(?<!\d)0(?:1\d|2|[3-6]\d)[-. ]\d{3,4}[-. ]\d{4}(?!\d)' },
        @{ name = 'phone number';    pattern = '(?<!\d)\d{3}[-. ]\d{3}[-. ]\d{4}(?!\d)' },
        @{ name = 'street address';  pattern = '(?i)\d{3,5}\s+Mitch\s+Daniels' },
        @{ name = 'date of birth';   pattern = '(?<!\d)19\d{2}-\d{2}-\d{2}(?!\d)' },
        @{ name = 'GPA';             pattern = '(?<!\d)[0-4]\.\d{1,2}\s*/\s*4\.5(?!\d)' }
    )
    # Key-based detection as well. The patent gazette this record was built from prints
    # every inventor's home address, so the risk is a field being carried over wholesale
    # rather than a value happening to look wrong.
    $forbiddenKeys = 'address|addr|home|residence|phone|mobile|cell|tel|birth|dob|gpa|ssn|passport|gender|nationality'

    $inExclude = $false
    $found = @()
    foreach ($line in ($Text -split "`n")) {
        if ($line -match '^[A-Za-z_]') { $inExclude = ($line -match '^exclude\s*:') }
        if ($inExclude) { continue }
        if ($line.TrimStart().StartsWith('#')) { continue }
        $k = [regex]::Match($line, '^\s*([A-Za-z_][A-Za-z0-9_]*)\s*:')
        if ($k.Success -and $k.Groups[1].Value -match "(?i)^($forbiddenKeys)$") {
            $found += "key '$($k.Groups[1].Value)': $($line.Trim())"
        }
        foreach ($f in $forbidden) { if ($line -match $f.pattern) { $found += "$($f.name): $($line.Trim())" } }
    }

    if ($found.Count -gt 0) {
        Write-Host ""
        Write-Host "SYNC REFUSED - $Label contains data the record marks as never-publish." -ForegroundColor Red
        Write-Host ""
        foreach ($f in $found) { Write-Host "    $f" -ForegroundColor Yellow }
        Write-Host ""
        Write-Host "  It is marked public_safe, but this check does not take that on trust."
        Write-Host "  Remove the value; it belongs in the narrative record, which is never copied here."
        Write-Host ""
        exit 3
    }
}

